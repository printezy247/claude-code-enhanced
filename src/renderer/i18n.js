let lang = 'en';

export function setLang(next) {
  lang = dict[next] ? next : 'en';
  return lang;
}
export function getLang() { return lang; }

export function t(key) {
  const k = String(key);
  return (dict[lang] && dict[lang][k]) || dict.en[k] || k;
}

/** t() with {name} placeholders filled from `vars`. */
export function tf(key, vars = {}) {
  return t(key).replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined ? m : String(vars[k])));
}

/** True when English has this key (the source of truth the others are checked against). */
export function hasKey(key) { return Object.prototype.hasOwnProperty.call(dict.en, String(key)); }

/** The keys of one locale, for tests. */
export function keysOf(code) { return Object.keys(dict[code] || {}); }

/** Locales missing keys that en has — the test asserts this stays empty. */
export function incompleteLocales() {
  const missing = [];
  const enKeys = Object.keys(dict.en);
  for (const code of LOCALES) {
    if (code === 'en') continue;
    const lack = enKeys.filter((k) => !dict[code][k]);
    if (lack.length) missing.push({ locale: code, keys: lack });
  }
  return missing;
}

/** Apply translations to every [data-i18n] element in the page. */
export function applyLang(root) {
  const doc = root || (typeof document !== 'undefined' ? document : null);
  if (!doc) return 0;
  let n = 0;
  for (const el of doc.querySelectorAll('[data-i18n]')) {
    el.textContent = t(el.getAttribute('data-i18n'));
    n++;
  }
  return n;
}
